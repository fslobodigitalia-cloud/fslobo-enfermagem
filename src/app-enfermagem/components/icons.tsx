export type AppIconProps = Omit<React.SVGProps<SVGSVGElement>, "ref"> & {
  size?: number | string;
  strokeWidth?: number | string;
};

function makeIcon(name: string, nodes: React.ReactNode) {
  const Icon = React.forwardRef<SVGSVGElement, AppIconProps>(({ size = 24, strokeWidth = 2, ...rest }, ref) => (
    <svg
      ref={ref}
      xmlns="http://www.w3.org/2000/svg"
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      {...rest}
    >
      {nodes}
    </svg>
  ));
  Icon.displayName = name;
  return Icon;
}

